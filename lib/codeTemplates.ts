// ── Feature 3 — Custom CSS Table ──────────────────────────────────────────
export function generateCustomTableCode(_config: Record<string, any>): string {
  return [
    '"use client";',
    "",
    "/**",
    " * AB UI — Lightweight Custom CSS Table (zero external deps)",
    " */",
    "",
    'import React, { useState } from "react";',
    'import { ChevronUp, ChevronDown, ChevronLeft, ChevronRight } from "lucide-react";',
    "",
    "const SAMPLE = [",
    "  { id: 101, name: 'Alice Johnson', department: 'Engineering', status: 'Active',   salary: 95000, rating: 4.8 },",
    "  { id: 102, name: 'Bob Smith',     department: 'Design',      status: 'Active',   salary: 78000, rating: 4.2 },",
    "  { id: 103, name: 'Carol Davis',   department: 'Product',     status: 'On Leave', salary: 88000, rating: 4.5 },",
    "];",
    "",
    "export default function CustomTable() {",
    "  const [sortField, setSortField]     = useState<string|null>(null);",
    "  const [sortDir, setSortDir]         = useState<'asc'|'desc'>('asc');",
    "  const [page, setPage]               = useState(1);",
    "  const pageSize = 5;",
    "",
    "  const sorted = [...SAMPLE].sort((a,b) => {",
    "    if (!sortField) return 0;",
    "    const av = (a as any)[sortField], bv = (b as any)[sortField];",
    "    return sortDir === 'asc' ? (av > bv ? 1 : -1) : (bv > av ? 1 : -1);",
    "  });",
    "",
    "  const rows = sorted.slice((page-1)*pageSize, page*pageSize);",
    "  const total = Math.ceil(SAMPLE.length / pageSize);",
    "",
    "  const handleSort = (f: string) => {",
    "    if (sortField === f) setSortDir(d => d === 'asc' ? 'desc' : 'asc');",
    "    else { setSortField(f); setSortDir('asc'); }",
    "  };",
    "",
    "  return (",
    '    <div className="w-full bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-xl overflow-hidden shadow-sm">',
    "      <div className='overflow-x-auto'>",
    "        <table className='w-full text-left text-sm'>",
    "          <thead>",
    "            <tr className='bg-slate-50 dark:bg-slate-950/20 border-b border-slate-200 dark:border-slate-800 text-slate-500 font-bold'>",
    "              {['id','name','department','status','salary'].map(f => (",
    "                <th key={f} onClick={() => handleSort(f)} className='px-6 py-4 cursor-pointer hover:bg-slate-100 dark:hover:bg-slate-800 uppercase text-xs'>",
    "                  {f} {sortField===f && (sortDir==='asc' ? <ChevronUp size={12} className='inline' /> : <ChevronDown size={12} className='inline' />)}",
    "                </th>",
    "              ))}",
    "            </tr>",
    "          </thead>",
    "          <tbody className='divide-y divide-slate-100 dark:divide-slate-800'>",
    "            {rows.map(r => (",
    "              <tr key={r.id} className='hover:bg-slate-50/50 dark:hover:bg-slate-800/20'>",
    "                <td className='px-6 py-4 font-mono'>{r.id}</td>",
    "                <td className='px-6 py-4 font-bold'>{r.name}</td>",
    "                <td className='px-6 py-4'>{r.department}</td>",
    "                <td className='px-6 py-4'><span className='px-2 py-0.5 rounded-full text-xs font-bold bg-green-100 text-green-800'>{r.status}</span></td>",
    "                <td className='px-6 py-4'>${r.salary.toLocaleString()}</td>",
    "              </tr>",
    "            ))}",
    "          </tbody>",
    "        </table>",
    "      </div>",
    "      <div className='flex items-center justify-between px-6 py-3 border-t border-slate-200 dark:border-slate-800 text-xs text-slate-500'>",
    "        <span>Page <b>{page}</b> of <b>{total}</b></span>",
    "        <div className='flex gap-1'>",
    "          <button onClick={() => setPage(p => Math.max(1,p-1))} disabled={page===1} className='p-1.5 rounded border hover:bg-slate-50 disabled:opacity-40'><ChevronLeft size={14}/></button>",
    "          <button onClick={() => setPage(p => Math.min(total,p+1))} disabled={page===total} className='p-1.5 rounded border hover:bg-slate-50 disabled:opacity-40'><ChevronRight size={14}/></button>",
    "        </div>",
    "      </div>",
    "    </div>",
    "  );",
    "}",
  ].join("\n");
}

