// ── Feature 1 ─────────────────────────────────────────────────────────────
export function generateTagBoardCode(config: Record<string, any>): string {
  const cardCount = Number(config.cardCount ?? 12);
  const columns = Number(config.columns ?? 4);

  const gridColClass =
    columns === 1
      ? "grid-cols-1"
      : columns === 2
      ? "grid-cols-1 md:grid-cols-2"
      : columns === 3
      ? "grid-cols-1 md:grid-cols-2 lg:grid-cols-3"
      : "grid-cols-1 md:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4";

  return [
    '"use client";',
    "",
    "/**",
    " * AB UI — Student Class Assignment Board",
    " * Dependencies: @dnd-kit/core  @dnd-kit/utilities  lucide-react",
    " */",
    "",
    'import React, { useState, useMemo } from "react";',
    'import { DndContext, DragOverlay, PointerSensor, MouseSensor, TouchSensor, useSensor, useSensors, useDraggable, useDroppable } from "@dnd-kit/core";',
    'import { CSS } from "@dnd-kit/utilities";',
    'import { UserCircle2, Users, Search, X } from "lucide-react";',
    "",
    "interface Person { id: string; name: string; }",
    "",
    "/* ── Mock roster (replace with your API call) ── */",
    "const STUDENTS: Person[] = [",
    '  { id: "s01", name: "Alice Johnson" },',
    '  { id: "s02", name: "Bob Smith" },',
    '  { id: "s03", name: "Carol Williams" },',
    '  // ... add more students',
    "];",
    "",
    "const CARDS = Array.from({ length: " + cardCount + " }, (_, i) => ({",
    "  id: `card-${i + 1}`,",
    "  label: `Class ${i + 1}`,",
    "}));",
    "",
    "/* ── PersonChip — drag from anywhere ─────────── */",
    "function PersonChip({ person, inCard, assignedTo, onRemove, overlay, sourceId }: {",
    "  person: Person; inCard?: boolean; assignedTo?: string; onRemove?: () => void;",
    "  overlay?: boolean; sourceId?: string;",
    "}) {",
    "  const { attributes, listeners, setNodeRef, transform, isDragging } = useDraggable({",
    "    id: sourceId ?? `person-${person.id}`,",
    "    data: { person },",
    "    disabled: overlay,",
    "  });",
    "  const style = transform ? { transform: CSS.Translate.toString(transform) } : undefined;",
    "",
    "  if (overlay) return (",
    '    <div className="inline-flex items-center gap-2 px-3.5 py-2 rounded-lg bg-blue-600 text-white text-xs font-bold shadow-xl cursor-grabbing pointer-events-none">',
    "      <UserCircle2 size={13} /><span>{person.name}</span>",
    "    </div>",
    "  );",
    "",
    "  return (",
    "    <div ref={setNodeRef} style={style} {...listeners} {...attributes}",
    "      className={`inline-flex items-center gap-2 px-3 py-1.5 rounded-lg text-xs font-semibold border select-none cursor-grab active:cursor-grabbing transition-all",
    "        ${isDragging ? 'opacity-20 scale-90' : inCard",
    "          ? 'bg-blue-50 text-blue-700 border-blue-200 hover:bg-blue-100 dark:bg-blue-950/50 dark:text-blue-300 dark:border-blue-800'",
    "          : assignedTo",
    "          ? 'bg-amber-50 text-amber-700 border-amber-200 dark:bg-amber-950/40 dark:text-amber-300 dark:border-amber-800'",
    "          : 'bg-white text-slate-700 border-slate-200 hover:border-blue-300 dark:bg-slate-800 dark:text-slate-300 dark:border-slate-700'",
    "        }`}",
    "    >",
    "      <UserCircle2 size={12} className=\"opacity-60\" />",
    "      <span>{person.name}</span>",
    "      {assignedTo && !inCard && (",
    '        <span className="px-1.5 py-0.5 rounded text-[9px] font-bold bg-amber-100 text-amber-600 dark:bg-amber-900/50 dark:text-amber-400">{assignedTo}</span>',
    "      )}",
    "      {inCard && onRemove && (",
    "        <button onPointerDown={(e)=>e.stopPropagation()} onClick={(e)=>{e.stopPropagation();onRemove();}}",
    '          className="w-4 h-4 flex items-center justify-center rounded hover:bg-blue-200 dark:hover:bg-blue-800 text-blue-400 cursor-pointer">',
    "          <X size={10} />",
    "        </button>",
    "      )}",
    "    </div>",
    "  );",
    "}",
    "",
    "/* ── ClassCard ───────────────────────────────── */",
    "function ClassCard({ id, label, people, onRemove }: { id: string; label: string; people: Person[]; onRemove: (pid: string) => void }) {",
    "  const { setNodeRef, isOver } = useDroppable({ id });",
    "  return (",
    "    <div ref={setNodeRef}",
    "      className={`flex flex-col rounded-xl border min-h-[160px] transition-all overflow-hidden",
    "        ${isOver ? 'border-blue-500 shadow-lg ring-2 ring-blue-500/20 scale-[1.02]' : 'border-slate-200 dark:border-slate-800'}`,",
    "    }>",
    "      <div className={`flex items-center justify-between px-4 py-3 border-b transition-all",
    "        ${isOver ? 'bg-blue-600 border-blue-500' : 'bg-slate-50 dark:bg-slate-900 border-slate-100 dark:border-slate-800'}`}>",
    "        <div className='flex items-center gap-2'>",
    "          <Users size={13} className={isOver ? 'text-blue-100' : 'text-slate-400'} />",
    "          <span className={`text-xs font-extrabold ${isOver ? 'text-white' : 'text-foreground'}`}>{label}</span>",
    "        </div>",
    "        <span className={`text-[10px] font-bold px-2 py-0.5 rounded-full",
    "          ${isOver ? 'bg-white/20 text-white' : 'bg-slate-100 dark:bg-slate-800 text-slate-400'}`}>{people.length}</span>",
    "      </div>",
    "      <div className={`flex-1 p-3 transition-all ${isOver ? 'bg-blue-50/40 dark:bg-blue-950/15' : 'bg-white dark:bg-slate-900/50'}`}>",
    "        {people.length > 0 ? (",
    "          <div className='flex flex-wrap gap-1.5'>",
    "            {people.map(p => <PersonChip key={p.id} person={p} inCard sourceId={`card-${id}-${p.id}`} onRemove={() => onRemove(p.id)} />)}",
    "          </div>",
    "        ) : (",
    "          <div className={`flex-1 flex flex-col items-center justify-center rounded-lg border border-dashed min-h-[80px]",
    "            ${isOver ? 'border-blue-400 bg-blue-50/60' : 'border-slate-200 dark:border-slate-800'}`}>",
    "            <span className={`text-[10px] font-semibold uppercase tracking-wide",
    "              ${isOver ? 'text-blue-500' : 'text-slate-300 dark:text-slate-700'}`}>",
    "              {isOver ? 'Drop to assign' : 'Drop students here'}",
    "            </span>",
    "          </div>",
    "        )}",
    "      </div>",
    "    </div>",
    "  );",
    "}",
    "",
    "/* ── Main Board ─────────────────────────────── */",
    "export default function StudentClassBoard() {",
    "  const [assignment, setAssignment] = useState<Record<string,string>>({});",
    "  const [activePerson, setActivePerson] = useState<Person|null>(null);",
    "  const [search, setSearch] = useState('');",
    "",
    "  const sensors = useSensors(",
    "    useSensor(PointerSensor, { activationConstraint: { distance: 4 } }),",
    "    useSensor(MouseSensor,   { activationConstraint: { distance: 4 } }),",
    "    useSensor(TouchSensor,   { activationConstraint: { delay: 150, tolerance: 8 } }),",
    "  );",
    "",
    "  const filtered = STUDENTS.filter(p => p.name.toLowerCase().includes(search.toLowerCase()));",
    "  const unassigned = filtered.filter(p => !assignment[p.id]);",
    "  const assigned   = filtered.filter(p => !!assignment[p.id]);",
    "",
    "  const cardLabelMap = Object.fromEntries(CARDS.map(c => [c.id, c.label]));",
    "",
    "  const handleDragEnd = (e: any) => {",
    "    const { active, over } = e;",
    "    setActivePerson(null);",
    "    if (!over) return;",
    "    const person = active.data.current?.person as Person;",
    "    if (!person || !String(over.id).startsWith('card-')) return;",
    "    setAssignment(prev => ({ ...prev, [person.id]: String(over.id) }));",
    "  };",
    "",
    "  return (",
    "    <DndContext sensors={sensors} onDragStart={e => setActivePerson(e.active.data.current?.person)} onDragEnd={handleDragEnd}>",
    "      <div className='flex flex-col gap-6'>",
    "        {/* Search Panel */}",
    "        <div className='bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-xl p-5 shadow-sm'>",
    "          <div className='relative mb-4'>",
    "            <Search size={15} className='absolute left-3 top-1/2 -translate-y-1/2 text-slate-400' />",
    "            <input type='text' placeholder='Search students…' value={search} onChange={e=>setSearch(e.target.value)}",
    "              className='w-full pl-9 pr-4 py-2.5 text-sm rounded-lg border border-slate-200 dark:border-slate-800 bg-slate-50 dark:bg-slate-950 outline-none focus:ring-2 focus:ring-blue-500/40' />",
    "          </div>",
    "          {unassigned.length > 0 && <div className='flex flex-wrap gap-2'>{unassigned.map(p => <PersonChip key={p.id} person={p} sourceId={`search-${p.id}`} />)}</div>}",
    "          {assigned.length > 0 && (",
    "            <div className='mt-3 flex flex-wrap gap-2'>",
    "              {assigned.map(p => <PersonChip key={p.id} person={p} assignedTo={cardLabelMap[assignment[p.id]]} sourceId={`search-${p.id}`} />)}",
    "            </div>",
    "          )}",
    "        </div>",
    "",
    "        {/* Class Cards */}",
    `        <div className="grid ${gridColClass} gap-4">`,
    "          {CARDS.map(card => (",
    "            <ClassCard key={card.id} id={card.id} label={card.label}",
    "              people={STUDENTS.filter(p => assignment[p.id] === card.id)}",
    "              onRemove={pid => setAssignment(prev => { const n={...prev}; delete n[pid]; return n; })} />",
    "          ))}",
    "        </div>",
    "      </div>",
    "      <DragOverlay>",
    "        {activePerson && <PersonChip person={activePerson} overlay />}",
    "      </DragOverlay>",
    "    </DndContext>",
    "  );",
    "}",
  ].join("\n");
}

// ── Feature 2 ─────────────────────────────────────────────────────────────
export function generateWelcomeScreenCode(config: Record<string, any>): string {
  const name = String(config.name ?? "Developer");
  const systemName = String(config.systemName ?? "AB UI Kit");
  const nameColor = String(config.nameColor ?? "#ef4444");
  const duration = Number(config.animateDuration ?? 0.8);
  const delay = Number(config.delayBeforeOut ?? 1800);
  const skippable = Boolean(config.skippable ?? true);

  return [
    '"use client";',
    "",
    '/**',
    ' * AB UI — Welcome / Splash Screen',
    ' * Dependencies: framer-motion',
    ' */',
    "",
    'import { useEffect, useState } from "react";',
    'import { motion, AnimatePresence } from "framer-motion";',
    "",
    "export default function WelcomeSplashScreen() {",
    "  const [visible, setVisible] = useState(true);",
    "",
    "  useEffect(() => {",
    "    const timer = setTimeout(() => setVisible(false), " + delay + ");",
    "    return () => clearTimeout(timer);",
    "  }, []);",
    "",
    "  if (!visible) return null;",
    "",
    "  return (",
    "    <AnimatePresence>",
    "      <motion.div",
    '        className="fixed inset-0 z-50 flex flex-col items-center justify-center bg-slate-950 select-none"',
    "        style={{ background: 'linear-gradient(135deg, #0f172a 0%, #020617 100%)' }}",
    "        initial={{ opacity: 0 }}",
    "        animate={{ opacity: 1 }}",
    "        exit={{ opacity: 0, scale: 1.05 }}",
    "        transition={{ duration: " + duration + ", ease: 'easeInOut' }}",
    skippable ? "        onClick={() => setVisible(false)}" : "",
    "      >",
    "        <div className='text-center px-4'>",
    "          <motion.h1",
    '            className="text-5xl font-bold tracking-tight text-white"',
    "            initial={{ y: 20, opacity: 0 }}",
    "            animate={{ y: 0, opacity: 1 }}",
    "            transition={{ delay: 0.2, duration: 0.6 }}",
    "          >",
    '            Hello, <span style={{ color: "' + nameColor + '" }}>' + name + "</span>",
    "          </motion.h1>",
    "          <motion.p",
    '            className="text-lg text-slate-400 font-light mt-2"',
    "            initial={{ y: 15, opacity: 0 }}",
    "            animate={{ y: 0, opacity: 1 }}",
    "            transition={{ delay: 0.4, duration: 0.6 }}",
    "          >",
    "            " + systemName,
    "          </motion.p>",
    "        </div>",
    skippable ? '        <p className="absolute bottom-8 text-xs text-slate-500">Click anywhere to skip</p>' : "",
    "      </motion.div>",
    "    </AnimatePresence>",
    "  );",
    "}",
  ].join("\n");
}

